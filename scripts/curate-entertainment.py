#!/usr/bin/env python3
"""Build config/entertainment/pack.yaml from Internet Archive items.

For each item the smallest phone-friendly file (or every chapter at 64 kbps)
is chosen; whatever license the archive lists is noted alongside it.

    build/venv/bin/python scripts/curate-entertainment.py
"""
from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

import yaml

OUT = Path(__file__).resolve().parent.parent / "config" / "entertainment" / "pack.yaml"
UA = {"User-Agent": "Pergamon-curate"}
# (archive.org identifier, kind, file pattern or None for automatic, in the sampler?)
CANDIDATES = [
    ("charlie_chaplin_film_fest", "film", r"_512kb\.mp4$", True),
    ("gullivers_travels1939", "film", r"_512kb\.mp4$", True),
    ("his_girl_friday", "film", r"_512kb\.mp4$", False),
    ("TheGeneral1926", "film", r"_512kb\.mp4$", False),
    ("Sita_Sings_the_Blues", "film", r"^Sita_Sings_the_Blues_small\.mp4$", False),
    ("superman_the_mechanical_monsters", "film", r"_512kb\.mp4$", True),
    ("art_of_war_librivox", "audiobook", r"_64kb\.mp3$", True),
    ("peter_pan_0707_librivox", "audiobook", r"_64kb\.mp3$", True),
    ("tom_sawyer_librivox", "audiobook", r"_64kb\.mp3$", False),
    ("adventures_holmes", "audiobook", r"_64kb\.mp3$", False),
    ("treasureisland_librivox", "audiobook", r"_64kb\.mp3$", False),
    ("thejunglebook_pc_librivox", "audiobook", r"_64kb\.mp3$", False),
    ("pride_and_prejudice_librivox", "audiobook", r"_64kb\.mp3$", False),
    ("Musopen-Libre", "music", r"\.mp3$", True),
]
REDISTRIBUTABLE = re.compile(r"creativecommons\.org/(licenses/(publicdomain|by(-sa|-nc|-nd|-nc-sa|-nc-nd)?)/|publicdomain/(mark|zero)/)")


def license_name(url: str) -> str:
    if not url:
        return "not recorded"
    if "publicdomain/zero" in url:
        return "CC0 (public domain)"
    if "publicdomain" in url:
        return "Public domain"
    m = re.search(r"licenses/([a-z-]+)/([\d.]+)", url)
    return f"CC {m.group(1).upper()} {m.group(2)}" if m else url


def main() -> int:
    items, skipped = [], []
    for ident, kind, pattern, sampler in CANDIDATES:
        with urllib.request.urlopen(urllib.request.Request(f"https://archive.org/metadata/{ident}", headers=UA),
                                    timeout=60) as r:
            d = json.load(r)
        m = d.get("metadata") or {}
        lic = m.get("licenseurl") or ""
        files = sorted((f for f in d["files"] if re.search(pattern, f["name"])), key=lambda f: f["name"])
        if not files:
            skipped.append(f"{ident}: no file matching {pattern}")
            continue
        title = m.get("title") if isinstance(m.get("title"), str) else (m.get("title") or [ident])[0]
        creator = m.get("creator") if isinstance(m.get("creator"), str) else ", ".join(m.get("creator") or [])
        items.append({
            "id": ident, "kind": kind, "title": title, "creator": creator or "",
            "year": str(m.get("year") or m.get("date") or "")[:4],
            "license": license_name(lic), "license_url": lic,
            "source": f"https://archive.org/details/{ident}",
            "sampler": sampler,
            "files": [{"name": f["name"], "bytes": int(f.get("size") or 0),
                       "seconds": round(float(f["length"])) if re.fullmatch(r"[\d.]+", str(f.get("length", ""))) else None}
                      for f in files],
        })
    for s in skipped:
        print("skipped", s, file=sys.stderr)
    OUT.write_text("# Generated by scripts/curate-entertainment.py: every item's license\n"
                   "# allows redistribution, recorded with it. Edit CANDIDATES there, not here.\n"
                   + yaml.safe_dump({"items": items}, sort_keys=False, allow_unicode=True, width=100))
    total = lambda only: sum(f["bytes"] for i in items if not only or i["sampler"] for f in i["files"])  # noqa: E731
    print(f"{len(items)} items; sampler {total(True) / 1e9:.1f} GB, full {total(False) / 1e9:.1f} GB → {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
